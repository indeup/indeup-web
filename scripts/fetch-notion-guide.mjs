// Fetches published articles from the "인디업 블로그 원고" Notion database and
// writes data/guide/notion-articles.json in the same shape as the
// hand-written GuideArticle entries in src/lib/guideArticles.ts (which
// imports and merges this file at build time — see that file).
//
// Run by .github/workflows/naver-blog-rss.yml on a schedule. Never fetched
// from the browser — NOTION_TOKEN is a server-only secret (.env.local
// locally, a GitHub Actions secret in CI) and this script's only output is
// the plain-text JSON file the site reads at build time.
//
// On any request failure (network error, bad auth, non-2xx response) the
// script exits non-zero WITHOUT touching the existing JSON file, so a
// transient Notion outage never wipes out the last known-good articles.
// Individual rows with missing/invalid required fields are skipped with a
// warning rather than failing the whole run — one bad draft shouldn't take
// down every other article.

import { writeFile, readFile } from "node:fs/promises";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.join(__dirname, "..");
const OUTPUT_PATH = path.join(rootDir, "data", "guide", "notion-articles.json");
const SLUG_HISTORY_PATH = path.join(rootDir, "data", "guide", "notion-slug-history.json");
const REDIRECTS_PATH = path.join(rootDir, "data", "guide", "notion-redirects.json");
const HTACCESS_PATH = path.join(rootDir, "public", ".htaccess");
const REDIRECTS_BEGIN = "# BEGIN NOTION GUIDE REDIRECTS (auto-generated by scripts/fetch-notion-guide.mjs — do not edit by hand)";
const REDIRECTS_END = "# END NOTION GUIDE REDIRECTS";

const NOTION_DATABASE_ID = "3b200c04-3142-80c1-aa57-fdd094477567";
const NOTION_API_VERSION = "2022-06-28";
const NOTION_API_BASE = "https://api.notion.com/v1";

// Must match GuideCategory in src/lib/guideArticles.ts exactly. Kept as a
// plain array (not imported) because this is a standalone Node script and
// that file is TypeScript with non-JSON imports.
const VALID_CATEGORIES = [
  "원룸 책상",
  "컴퓨터 책상",
  "2인용 책상",
  "책상 깊이",
  "책상 높이",
  "공간 배치",
  "맞춤 제작",
];

const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

function loadEnvLocal() {
  const envPath = path.join(rootDir, ".env.local");
  if (!existsSync(envPath)) return;
  for (const line of readFileSync(envPath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    if (!(key in process.env)) process.env[key] = trimmed.slice(eq + 1).trim();
  }
}

loadEnvLocal();

const NOTION_TOKEN = process.env.NOTION_TOKEN;

async function notionFetch(endpoint, options = {}) {
  const res = await fetch(`${NOTION_API_BASE}${endpoint}`, {
    ...options,
    headers: {
      Authorization: `Bearer ${NOTION_TOKEN}`,
      "Notion-Version": NOTION_API_VERSION,
      "Content-Type": "application/json",
      ...options.headers,
    },
  });
  if (!res.ok) {
    const body = await res.text().catch(() => "");
    throw new Error(`Notion API ${endpoint} failed: ${res.status} ${res.statusText} ${body}`);
  }
  return res.json();
}

async function queryPublishedPages() {
  const pages = [];
  let cursor;
  do {
    const body = {
      filter: { property: "상태", select: { equals: "발행" } },
      ...(cursor && { start_cursor: cursor }),
    };
    const data = await notionFetch(`/databases/${NOTION_DATABASE_ID}/query`, {
      method: "POST",
      body: JSON.stringify(body),
    });
    pages.push(...data.results);
    cursor = data.has_more ? data.next_cursor : undefined;
  } while (cursor);
  return pages;
}

async function fetchAllBlocks(blockId) {
  const blocks = [];
  let cursor;
  do {
    const qs = new URLSearchParams({ page_size: "100", ...(cursor && { start_cursor: cursor }) });
    const data = await notionFetch(`/blocks/${blockId}/children?${qs}`);
    blocks.push(...data.results);
    cursor = data.has_more ? data.next_cursor : undefined;
  } while (cursor);
  return blocks;
}

function richTextToPlain(richTextArray) {
  return (richTextArray ?? []).map((rt) => rt.plain_text ?? "").join("").trim();
}

const LIST_TYPES = new Set(["bulleted_list_item", "numbered_list_item"]);
const HEADING_TYPES = new Set(["heading_1", "heading_2", "heading_3"]);

// Tested standalone against realistic Notion block shapes — see
// scratchpad test-blocks.mjs this was lifted from.
function blocksToSections(blocks) {
  const sections = [];
  let current = { heading: "", body: [], list: [] };
  const pushCurrent = () => {
    if (current.heading || current.body.length > 0 || current.list.length > 0) {
      sections.push({
        heading: current.heading,
        body: current.body,
        ...(current.list.length > 0 && { list: current.list }),
      });
    }
  };
  for (const block of blocks) {
    const type = block.type;
    if (HEADING_TYPES.has(type)) {
      pushCurrent();
      current = { heading: richTextToPlain(block[type]?.rich_text), body: [], list: [] };
    } else if (type === "paragraph") {
      const text = richTextToPlain(block.paragraph?.rich_text);
      if (text) current.body.push(text);
    } else if (LIST_TYPES.has(type)) {
      const text = richTextToPlain(block[type]?.rich_text);
      if (text) current.list.push(text);
    } else {
      console.warn(`  (skipping unsupported block type: ${type})`);
    }
  }
  pushCurrent();
  return sections;
}

function toDateOnly(isoString) {
  return isoString ? isoString.slice(0, 10) : undefined;
}

function extractArticle(page, blocks) {
  const props = page.properties;
  const title = richTextToPlain(props["이름"]?.title);
  const slug = richTextToPlain(props["슬러그"]?.rich_text);
  const description = richTextToPlain(props["설명"]?.rich_text);
  const categories = (props["카테고리"]?.multi_select ?? [])
    .map((o) => o.name)
    .filter((name) => VALID_CATEGORIES.includes(name));
  const relatedLabel = richTextToPlain(props["관련제품명"]?.rich_text);
  const relatedHref = richTextToPlain(props["관련제품링크"]?.rich_text);
  const publishedAtRaw = props["발행일"]?.date?.start;

  const problems = [];
  if (!title) problems.push("제목 없음");
  if (!slug || !SLUG_RE.test(slug)) problems.push(`슬러그 없음/형식 오류 (영문 소문자·숫자·하이픈만): "${slug}"`);
  if (!description) problems.push("설명 없음");
  if (categories.length === 0) problems.push("유효한 카테고리 없음");

  const sections = blocksToSections(blocks);
  if (sections.length === 0) problems.push("본문 없음 (헤딩/문단/목록 블록 하나도 없음)");

  if (problems.length > 0) {
    console.warn(`SKIP "${title || page.id}": ${problems.join(", ")}`);
    return null;
  }

  const publishedAt = toDateOnly(publishedAtRaw) ?? toDateOnly(page.created_time);
  const updatedAtCandidate = toDateOnly(page.last_edited_time);
  const updatedAt = updatedAtCandidate && updatedAtCandidate !== publishedAt ? updatedAtCandidate : undefined;

  return {
    pageId: page.id,
    slug,
    title,
    description,
    categories,
    sections,
    relatedProduct:
      relatedLabel && relatedHref
        ? { label: relatedLabel, href: relatedHref }
        : { label: "책상 가이드 더 보기", href: "/guide/" },
    publishedAt,
    ...(updatedAt && { updatedAt }),
  };
}

async function readJsonSafe(filePath, fallback) {
  try {
    return JSON.parse(await readFile(filePath, "utf-8"));
  } catch {
    return fallback;
  }
}

// Detects slug renames by comparing each page's current slug against the
// slug it had last run (keyed by Notion page ID, which never changes even
// when the slug does). Chains are collapsed so a slug that was renamed
// twice (A -> B -> C) still redirects straight from A to C, not to the
// now-dead B. Redirects whose "from" collides with a slug some article
// currently uses are dropped — an old slug should never shadow a live page.
function updateRedirects(previousHistory, previousRedirects, articles) {
  const history = { ...previousHistory };
  const redirects = new Map(previousRedirects.map((r) => [r.from, r.to]));
  const liveSlugs = new Set(articles.map((a) => a.slug));

  for (const article of articles) {
    const oldSlug = history[article.pageId];
    if (oldSlug && oldSlug !== article.slug) {
      for (const [from, to] of redirects) {
        if (to === oldSlug) redirects.set(from, article.slug);
      }
      redirects.set(oldSlug, article.slug);
      console.log(`Detected slug rename: "${oldSlug}" -> "${article.slug}"`);
    }
    history[article.pageId] = article.slug;
  }

  for (const from of redirects.keys()) {
    if (liveSlugs.has(from)) redirects.delete(from);
  }

  return {
    history,
    redirects: [...redirects.entries()].map(([from, to]) => ({ from, to })),
  };
}

async function writeRedirectsToHtaccess(redirects) {
  const body =
    redirects.length === 0
      ? "# (현재 리다이렉트 없음)"
      : [
          "<IfModule mod_rewrite.c>",
          "  RewriteEngine On",
          ...redirects.map(
            (r) => `  RewriteRule ^guide/${r.from}/?$ /guide/${r.to}/ [R=308,L]`
          ),
          "</IfModule>",
        ].join("\n");
  const block = `${REDIRECTS_BEGIN}\n${body}\n${REDIRECTS_END}`;

  const current = await readFile(HTACCESS_PATH, "utf-8");
  const markerRe = new RegExp(
    `${REDIRECTS_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${REDIRECTS_END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`
  );

  const next = markerRe.test(current)
    ? current.replace(markerRe, block)
    : current.replace("# ── 보안 헤더", `${block}\n\n# ── 보안 헤더`);

  await writeFile(HTACCESS_PATH, next, "utf-8");
}

async function main() {
  if (!NOTION_TOKEN) {
    throw new Error("Missing NOTION_TOKEN in .env.local (or environment)");
  }

  const pages = await queryPublishedPages();
  console.log(`Found ${pages.length} published page(s) in Notion.`);

  const articles = [];
  const seenSlugs = new Set();
  for (const page of pages) {
    const blocks = await fetchAllBlocks(page.id);
    const article = extractArticle(page, blocks);
    if (!article) continue;
    if (seenSlugs.has(article.slug)) {
      console.warn(`SKIP "${article.title}": duplicate slug "${article.slug}"`);
      continue;
    }
    seenSlugs.add(article.slug);
    articles.push(article);
  }

  const previousHistory = await readJsonSafe(SLUG_HISTORY_PATH, {});
  const previousRedirects = await readJsonSafe(REDIRECTS_PATH, []);
  const { history, redirects } = updateRedirects(previousHistory, previousRedirects, articles);

  await writeFile(SLUG_HISTORY_PATH, `${JSON.stringify(history, null, 2)}\n`, "utf-8");
  await writeFile(REDIRECTS_PATH, `${JSON.stringify(redirects, null, 2)}\n`, "utf-8");
  await writeRedirectsToHtaccess(redirects);

  const publishedArticles = articles.map(({ pageId, ...rest }) => rest);
  await writeFile(OUTPUT_PATH, `${JSON.stringify(publishedArticles, null, 2)}\n`, "utf-8");
  console.log(`Wrote ${publishedArticles.length} article(s) to ${OUTPUT_PATH}`);
}

main().catch(async (err) => {
  console.error("Notion guide fetch failed:", err.message);
  try {
    await readFile(OUTPUT_PATH, "utf-8");
    console.error("Existing data/guide/notion-articles.json left untouched.");
  } catch {
    console.error("No existing data/guide/notion-articles.json was found either.");
  }
  process.exit(1);
});
